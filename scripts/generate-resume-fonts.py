"""Losslessly package the existing resume fonts as WOFF2 (no character subsetting).

python -m pip install fonttools brotli
python scripts/generate-resume-fonts.py
"""
import hashlib
import io
import json
from pathlib import Path

from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = [
    ("Alibaba PuHuiTi", "AlibabaPuHuiTi-3-55-Regular.ttf", 400),
    ("Alibaba PuHuiTi", "AlibabaPuHuiTi-3-85-Bold.ttf", 700),
    ("MiSans", "MiSans-Normal.ttf", 400),
    ("MiSans", "MiSans-Medium.ttf", 700),
    ("Noto Sans SC", "NotoSansSC-Regular.otf", 400),
    ("Noto Sans SC", "NotoSansSC-Medium.otf", 500),
    ("Noto Sans SC", "NotoSansSC-Bold.otf", 700),
    ("Source Han Serif SC", "SourceHanSerifSC-Regular.otf", 400),
    ("Source Han Serif SC", "SourceHanSerifSC-Medium.otf", 500),
    ("Source Han Serif SC", "SourceHanSerifSC-Bold.otf", 700),
]

output = ROOT / "public/fonts/resume"
output.mkdir(parents=True, exist_ok=True)
manifest = {}
rules = ['/* Generated by scripts/generate-resume-fonts.py. */', '@import "../styles/newsreader.css";\n']
for family, filename, weight in FONTS:
    source = ROOT / "public/fonts" / filename
    font = TTFont(source, recalcTimestamp=False)
    font.flavor = "woff2"
    buffer = io.BytesIO()
    font.save(buffer)
    data = buffer.getvalue()
    packed = TTFont(io.BytesIO(data))
    # Preserve every mapped character and its advance width for identical layout.
    assert font.getBestCmap() == packed.getBestCmap(), filename
    assert font["hmtx"].metrics == packed["hmtx"].metrics, filename
    name = f"{source.stem}.{hashlib.sha256(data).hexdigest()[:12]}.woff2"
    (output / name).write_bytes(data)
    url = f"/fonts/resume/{name}"
    manifest[filename] = url
    rules.append(f'''@font-face {{
  font-family: "{family}";
  src: url("{url}") format("woff2");
  font-weight: {weight};
  font-style: normal;
  font-display: swap;
}}
''')
    print(f"{filename}: {source.stat().st_size / 1048576:.2f} -> {len(data) / 1048576:.2f} MiB")

(ROOT / "src/generated/resume-fonts.json").write_text(json.dumps(manifest, indent=2) + "\n")
(ROOT / "src/app/font.css").write_text("\n".join(rules))
