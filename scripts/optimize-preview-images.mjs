import { readFile, readdir, writeFile } from "node:fs/promises";
import { writeWebpAsset } from "./preview-image-assets.mjs";

const avatar = await writeWebpAsset("public/avatar.png", "/images/avatar", 1024, 90);
await writeFile("src/generated/defaultAvatar.ts",
  `// Generated by scripts/optimize-preview-images.mjs.\nexport const DEFAULT_AVATAR = ${JSON.stringify(avatar.url)};\n`);
console.log(`Default avatar: ${avatar.bytes} bytes`);

const manifestPath = "src/generated/templateSnapshotManifest.ts";
const existing = await readFile(manifestPath, "utf8");
const manifest = JSON.parse(existing.slice(existing.indexOf("{"), existing.lastIndexOf("}") + 1));
let total = 0;
for (const locale of ["zh", "en"]) {
  for (const filename of await readdir(`public/template-snapshots/${locale}`)) {
    if (!filename.endsWith(".png")) continue;
    const id = filename.slice(0, -4);
    const asset = await writeWebpAsset(
      `public/template-snapshots/${locale}/${filename}`,
      `/template-snapshots/${locale}/${id}`, 794, 82,
    );
    manifest.locales[locale][id] = asset.url;
    total += asset.bytes;
  }
}
await writeFile(manifestPath, `export const TEMPLATE_SNAPSHOT_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const;\n`);
console.log(`Template thumbnails: ${total} bytes`);
